var byShortcode = func() map[string]string {
	m := make(map[string]string, len(catalog))
	for _, e := range catalog {
		m[e.Description] = e.Char
	}
	return m
}()

var shortcodePattern = regexp.MustCompile(`:([a-z0-9_+-]+):`)

func All() []Entry {
	return catalog
}

// Lookup returns the emoji character for an exact shortcode match (e.g.
// "fire" for "\U0001f525"), and whether it was found.
func Lookup(shortcode string) (string, bool) {
	ch, ok := byShortcode[shortcode]
	return ch, ok
}

// Resolve replaces every ":shortcode:" in text with its matching emoji
// character, leaving unrecognized shortcodes untouched.
func Resolve(text string) string {
	return shortcodePattern.ReplaceAllStringFunc(text, func(match string) string {
		code := match[1 : len(match)-1]
		if ch, ok := byShortcode[code]; ok {
			return ch
		}
		return match
	})
}

func Search(query string) []Entry {
	query = strings.ToLower(strings.TrimSpace(query))
	if query == "" {
		return nil
	}

	type match struct {
		entry Entry
		score int
	}

	var matches []match
	for _, e := range catalog {
		if s := fuzzyScore(query, strings.ToLower(e.Description)); s > 0 {
			matches = append(matches, match{e, s})
		}
	}

	sort.SliceStable(matches, func(i, j int) bool {
		return matches[i].score > matches[j].score
	})

	results := make([]Entry, len(matches))
	for i, m := range matches {
		results[i] = m.entry
	}
	return results
}

func fuzzyScore(query, target string) int {
	qi := 0
	score := 0
	consecutive := 0
	for ti := 0; ti < len(target) && qi < len(query); ti++ {
		if target[ti] == query[qi] {
			score++
			if consecutive > 0 {
				score += 2
			}
			consecutive++
			qi++
		} else {
			consecutive = 0
		}
	}
	if qi < len(query) {
		return 0
	}

	switch {
	case target == query:
		score += 100
	case strings.HasPrefix(target, query):
		score += 50
	}
	return score
}
